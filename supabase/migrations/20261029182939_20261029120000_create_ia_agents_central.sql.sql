/*
# Central de Agentes IA — Schema for automated growth system

## Overview
Creates the data layer for the "Central de Agentes IA" panel: a hybrid architecture
where the visual interface + database live in Bolt/Supabase, while the heavy 24h
processing runs externally on Make.com and talks back via protected edge functions.

## Architecture: 3 Cells / 7 Agents
- Cell 1 (B2B Prospection & Sales): Agents 1-3 (Scraper, Enricher, Localized Copywriter)
- Cell 2 (PR & Media Authority):   Agents 4-5 (Journalist Tracker, Press Release Writer)
- Cell 3 (Content & Social):       Agents 6-7 (LinkedIn Posts, Video Scriptwriter)

## New Tables

1. `ia_leads` — Commercial leads generated by Cell 1.
   - empresa, pais, sector, tamano, director_rrhh_nombre, director_rrhh_email
   - email_redactado (AI-written personalized email), estado (pendiente/aprobado/enviado/respondido/descartado)
   - metricas: abierto, clicado, respondido, reunion_agendada
   - agente_origen, created_at, updated_at

2. `ia_press` — Press notes generated by Cell 2.
   - medio, tipo_medio, periodista_nombre, periodista_email, enfoque_articulo
   - email_propuesta (AI-written), estado (pendiente/aprobado/enviado/respondido/descartado)
   - metricas: abierto, clicado, mencion_conseguida
   - agente_origen, created_at, updated_at

3. `ia_metricas_diarias` — Daily aggregate metrics for the dashboard charts.
   - fecha, tipo (b2b / rrpp), enviados, aperturas, clics, respuestas, reuniones, menciones
   - Unique on (fecha, tipo)

4. `ia_config` — Single-row config table for filters + outbound webhook URL.
   - paises[], sectores[], tamano_min, tamano_max
   - tipos_medio[], keywords_rrpp[]
   - webhook_url, activo (whether the central is running)
   - ultima_activacion, ultimo_log_id

5. `ia_logs` — Console log entries from each of the 7 agents.
   - agente (1-7), celula (1-3), mensaje, nivel (info/ok/warn/error), created_at

## Security
- RLS enabled on every table.
- Grants to `authenticated` (admin-only panel) + `service_role` (edge functions).
- No `anon` access — these tables are private to the admin.
- Edge functions insert/update via service_role key (bypasses RLS but still needs the grant).
*/

-- =========================================================
-- ia_leads
-- =========================================================
CREATE TABLE IF NOT EXISTS ia_leads (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa text NOT NULL,
  pais text,
  sector text,
  tamano integer,
  director_rrhh_nombre text,
  director_rrhh_email text,
  email_redactado text,
  estado text NOT NULL DEFAULT 'pendiente',
  agente_origen text DEFAULT 'Agente 1-3',
  abierto boolean NOT NULL DEFAULT false,
  clicado boolean NOT NULL DEFAULT false,
  respondido boolean NOT NULL DEFAULT false,
  reunion_agendada boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE ia_leads ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON ia_leads TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON ia_leads TO service_role;

DROP POLICY IF EXISTS "ia_leads_select_authenticated" ON ia_leads;
CREATE POLICY "ia_leads_select_authenticated" ON ia_leads FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "ia_leads_insert_authenticated" ON ia_leads;
CREATE POLICY "ia_leads_insert_authenticated" ON ia_leads FOR INSERT
  TO authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "ia_leads_update_authenticated" ON ia_leads;
CREATE POLICY "ia_leads_update_authenticated" ON ia_leads FOR UPDATE
  TO authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "ia_leads_delete_authenticated" ON ia_leads;
CREATE POLICY "ia_leads_delete_authenticated" ON ia_leads FOR DELETE
  TO authenticated USING (true);

CREATE INDEX IF NOT EXISTS idx_ia_leads_estado ON ia_leads(estado);
CREATE INDEX IF NOT EXISTS idx_ia_leads_created_at ON ia_leads(created_at DESC);

